  var originals = new WeakMap();

  function t(key, vars) {
    var s = (JS[lang] && JS[lang][key]) || JS.fr[key] || key;
    if (vars) s = s.replace(/\{(\w+)\}/g, function (m, k) { return vars[k] != null ? vars[k] : ''; });
    return s;
  }

  function remember(el, prop, value) {
    var o = originals.get(el) || {};
    if (!(prop in o)) o[prop] = value;
    originals.set(el, o);
    return o[prop];
  }

  function apply() {
    document.documentElement.lang = lang;
    var nodes = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < nodes.length; i++) {
      var el = nodes[i], k = el.getAttribute('data-i18n');
      var fr = remember(el, 'text', el.textContent);
      el.textContent = pick(k) || fr;
    }
    nodes = document.querySelectorAll('[data-i18n-html]');
    for (i = 0; i < nodes.length; i++) {
      el = nodes[i]; k = el.getAttribute('data-i18n-html');
      var frHtml = remember(el, 'html', el.innerHTML);
      el.innerHTML = pick(k) || frHtml;
    }
    nodes = document.querySelectorAll('[data-i18n-attr]');
    for (i = 0; i < nodes.length; i++) {
      el = nodes[i];
      el.getAttribute('data-i18n-attr').split(';').forEach(function (pair) {
        var bits = pair.split(':'), attr = bits[0].trim(), key = (bits[1] || '').trim();
        if (!attr || !key) return;
        var frVal = remember(el, 'attr:' + attr, el.getAttribute(attr));
        var v = pick(key) || frVal;
        if (v != null) el.setAttribute(attr, v);
      });
    }
    nodes = document.querySelectorAll('[data-href-en], [data-href-de]');
    for (i = 0; i < nodes.length; i++) {
      el = nodes[i];
      var frHref = remember(el, 'href', el.getAttribute('href'));
      el.setAttribute('href', lang !== 'fr' && el.getAttribute('data-href-' + lang) ? el.getAttribute('data-href-' + lang) : frHref);
    }
    var tk = document.body && document.body.getAttribute('data-title');
    if (tk) {
      var frTitle = remember(document.body, 'title', document.title);
      document.title = pick(tk) ? pick(tk) + ' | Budget mensuel' : frTitle;
    }
    var dk = document.body && document.body.getAttribute('data-desc');
    var meta = document.querySelector('meta[name=description]');
    if (dk && meta) {
      var frDesc = remember(meta, 'content', meta.getAttribute('content'));
      meta.setAttribute('content', pick(dk) || frDesc);
    }
    var sw = document.querySelectorAll('[data-lang-switch]');
    for (i = 0; i < sw.length; i++) {
      sw[i].innerHTML = LANGS.map(function (l) {
        return '<button type="button" data-set-lang="' + l + '" lang="' + l + '" aria-label="' + NAMES[l] + '" aria-pressed="' + (lang === l) + '">' + l.toUpperCase() + '</button>';
      }).join('<span aria-hidden="true">/</span>');
    }
  }

  function setLang(l) {
    if (LANGS.indexOf(l) === -1) return;
    lang = l;
    try { localStorage.setItem(KEY, l); } catch (e) { /* ignoré */ }
    apply();
    document.dispatchEvent(new CustomEvent('langchange', { detail: l }));
  }

