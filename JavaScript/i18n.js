  function stored() {
    try { var v = localStorage.getItem(KEY); if (LANGS.indexOf(v) !== -1) return v; } catch (e) { /* ignoré */ }
    // Une page de texte allemande ou anglaise ouverte directement fixe la langue.
    var html = document.documentElement.getAttribute('lang');
    if (!document.documentElement.hasAttribute('data-dynamic') && LANGS.indexOf(html) !== -1) return html;
    var nav = (navigator.languages && navigator.languages[0]) || navigator.language || 'fr';
    return /^fr/i.test(nav) ? 'fr' : /^de/i.test(nav) ? 'de' : 'en';
  }

